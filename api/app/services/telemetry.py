"""RAG-specific Prometheus metrics (section 4.8). Request count and latency live in
routes/metrics.py; these are the ones the query pipeline increments."""

from __future__ import annotations

from prometheus_client import Counter, Histogram

BUCKETS = (0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 30, 60, 120)

RETRIEVAL_SECONDS = Histogram("rahbar_retrieval_seconds", "Embed + Chroma query", buckets=BUCKETS)
GENERATION_SECONDS = Histogram("rahbar_generation_seconds", "LLM call, per attempt", buckets=BUCKETS)
ABSTENTIONS = Counter("rahbar_abstentions_total", "Answers declined", ["reason"])
FALLBACKS = Counter("rahbar_fallbacks_total", "Safe canned responses after failure", ["reason"])
INVALID_CITATIONS = Counter("rahbar_invalid_citations_total", "Citations dropped: not retrieved")
GENERATION_RETRIES = Counter("rahbar_generation_retries_total", "Validation retries")
CACHE_HITS = Counter("rahbar_cache_hits_total", "Semantic cache hits")
CACHE_MISSES = Counter("rahbar_cache_misses_total", "Semantic cache misses")
TOKENS_IN = Counter("rahbar_tokens_in_total", "Prompt tokens sent to the model")
TOKENS_OUT = Counter("rahbar_tokens_out_total", "Tokens generated by the model")
